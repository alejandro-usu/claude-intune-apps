#!/usr/bin/env python3
"""Pin the Python packages of a packages app to exact Windows wheels.

For an app such as apps/PythonPackages/3.15, which lists the packages it installs in
requirements.in and depends on a Python app ("dependsOn": "Python/3.15"), this:
  1. resolves requirements.in and all its dependencies for 64-bit CPython <series> on Windows,
     with uv (pip on Linux or macOS would skip Windows-only dependencies)
  2. picks the wheel that Python on Windows would install for each, and checks its SHA-256
     against the hashes uv pinned
  3. writes source/requirements.txt (name==version --hash=sha256:...) for pip --require-hashes
  4. replaces "downloads" in app.json with those wheels' URLs and hashes

It doesn't change the app's version, Detect.ps1 or Install.ps1: it prints the versions of the
packages named in requirements.in, to copy into their $Expected lists.

Needs uv (pip install uv) and internet access to pypi.org.

Usage:
    python3 tools/pin_wheels.py PythonPackages/3.15
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.request

try:
    from packaging import tags
    from packaging.utils import canonicalize_name, parse_wheel_filename
except ImportError:
    from pip._vendor.packaging import tags
    from pip._vendor.packaging.utils import canonicalize_name, parse_wheel_filename

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build  # noqa: E402


def compile_requirements(requirements_in, series):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "requirements.txt")
        subprocess.run(["uv", "pip", "compile", requirements_in, "--python-platform", "x86_64-pc-windows-msvc",
                        "--python-version", series, "--only-binary", ":all:", "--generate-hashes",
                        "--no-header", "--no-annotate", "-o", out], check=True)
        with open(out, encoding="utf-8") as f:
            text = f.read()
    pins, current = {}, None
    for line in text.splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s\\]+)", line)
        if m:
            current = (m.group(1), m.group(2))
            pins[current] = set()
        if current:
            pins[current].update(re.findall(r"sha256:([0-9a-f]{64})", line))
    return pins


def pick_wheel(name, version, hashes, rank):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as response:
        files = json.load(response)["urls"]
    best = None
    for f in files:
        if not f["filename"].endswith(".whl"):
            continue
        r = min((rank[t] for t in parse_wheel_filename(f["filename"])[3] if t in rank), default=None)
        if r is not None and (best is None or r < best[0]):
            best = (r, f)
    if not best:
        sys.exit(f"{name}=={version}: no wheel for this Python on 64-bit Windows")
    f = best[1]
    if f["digests"]["sha256"] not in hashes:
        sys.exit(f"{f['filename']}: SHA-256 isn't one of the hashes uv pinned")
    return f


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("app", help="app path under apps/, e.g. PythonPackages/3.15")
    args = parser.parse_args()

    app_dir = os.path.join(build.APPS, args.app)
    manifest_path = os.path.join(app_dir, "app.json")
    with open(manifest_path, encoding="utf-8") as f:
        manifest = json.load(f)
    series = str(manifest.get("dependsOn", "")).rsplit("/", 1)[-1]
    if not re.fullmatch(r"3\.\d+", series):
        sys.exit(f'{args.app}: "dependsOn" must name a Python app, such as "Python/3.15"')
    major, minor = (int(p) for p in series.split("."))
    abi = f"cp{major}{minor}"
    supported = list(tags.cpython_tags(python_version=(major, minor), abis=[abi], platforms=["win_amd64"]))
    supported += list(tags.compatible_tags(python_version=(major, minor), interpreter=abi, platforms=["win_amd64"]))
    rank = {t: i for i, t in enumerate(supported)}

    requirements_in = os.path.join(app_dir, "requirements.in")
    pins = compile_requirements(requirements_in, series)
    wheels = []
    for (name, version), hashes in pins.items():
        f = pick_wheel(name, version, hashes, rank)
        wheels.append((canonicalize_name(name), version, f))

    with open(os.path.join(app_dir, "source", "requirements.txt"), "w", encoding="utf-8", newline="\n") as out:
        out.write(f"# Generated by tools/pin_wheels.py from requirements.in, for 64-bit CPython {series} on Windows.\n"
                  "# Install.ps1 installs exactly these, offline, with pip --require-hashes.\n")
        for name, version, f in wheels:
            out.write(f"{name}=={version} --hash=sha256:{f['digests']['sha256']}\n")

    manifest["downloads"] = [{"url": f["url"], "sha256": f["digests"]["sha256"]} for _, _, f in wheels]
    with open(manifest_path, "w", encoding="utf-8", newline="\n") as out:
        out.write(json.dumps(manifest, indent=2) + "\n")

    total = sum(f["size"] for _, _, f in wheels)
    print(f"Pinned {len(wheels)} wheels ({total / 1e6:.1f} MB) in source/requirements.txt and app.json.")
    with open(requirements_in, encoding="utf-8") as f:
        wanted = {canonicalize_name(re.split(r"[\s=<>!~;\[]", line.strip())[0])
                  for line in f if line.strip() and not line.lstrip().startswith("#")}
    print("Set $Expected in Detect.ps1 and source/Install.ps1 to:")
    for name, version, f in wheels:
        if name in wanted:
            print(f"    '{f['filename'].split('-')[0]}-{version}.dist-info'")


if __name__ == "__main__":
    main()
